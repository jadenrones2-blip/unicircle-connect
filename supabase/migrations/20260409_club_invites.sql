-- Club officers: users invited by the owner to co-manage a club
create table if not exists club_officers (
  id          uuid primary key default gen_random_uuid(),
  club_id     text not null,
  club_name   text not null,
  user_id     uuid not null references auth.users(id) on delete cascade,
  invited_by  uuid not null references auth.users(id),
  role        text not null default 'officer', -- 'officer' | 'evaluator'
  created_at  timestamptz default now(),
  unique (club_id, user_id)
);

alter table club_officers enable row level security;

create policy "Officers can read their own rows"
  on club_officers for select to authenticated
  using (user_id = auth.uid() or invited_by = auth.uid());

create policy "Owners can insert officers"
  on club_officers for insert to authenticated
  with check (invited_by = auth.uid());

create policy "Owners can delete officers they invited"
  on club_officers for delete to authenticated
  using (invited_by = auth.uid());

-- Club invites: one-time use tokens generated by the club owner
create table if not exists club_invites (
  id          uuid primary key default gen_random_uuid(),
  token       text not null unique default encode(gen_random_bytes(24), 'base64url'),
  club_id     text not null,
  club_name   text not null,
  created_by  uuid not null references auth.users(id) on delete cascade,
  used_by     uuid references auth.users(id),
  used_at     timestamptz,
  expires_at  timestamptz not null default (now() + interval '7 days'),
  role        text not null default 'officer',
  created_at  timestamptz default now()
);

alter table club_invites enable row level security;

-- Anyone with the token can read it (needed for the invite page before auth)
create policy "Public can read invite by token"
  on club_invites for select to anon, authenticated
  using (true);

-- Only the creator can insert
create policy "Owner can create invites"
  on club_invites for insert to authenticated
  with check (created_by = auth.uid());

-- Anyone authenticated can update (to mark used_by)
create policy "Authenticated can claim invite"
  on club_invites for update to authenticated
  using (used_by is null and expires_at > now());
